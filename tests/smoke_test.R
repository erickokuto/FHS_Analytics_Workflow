# Run from the app folder in RStudio: source('tests/smoke_test.R')
source('R/core.R')
source('R/importance.R')
source('R/plots.R')
x<-fhs_prepare(fhs_load('fhs.csv'))
stopifnot(nrow(x)==4434,all(c('randid','anychd','timechd','age1','illustrative_event_burden')%in%names(x)))
stopifnot(sum(as.character(x$prevchd1)=='Yes')==194)
stopifnot(nrow(fhs_catalogue(x))==ncol(x))
stopifnot(nrow(fhs_describe(x))>0,nrow(fhs_counts(x))>0)
s<-fhs_split(100,.70,.15);stopifnot(length(s$train)==70,length(s$validation)==15,length(s$test)==15)
z<-fhs_supervised(x,'anychd',c('age1','sex1','sysbp1'),'GLM / linear',.70,.15)
stopifnot(nrow(z$table)==1,is.finite(z$table$validation_metric[1]))
sv<-fhs_survival_frame(x,'anychd',c('age1','sex1'),TRUE)
stopifnot(nrow(sv)==4240,all(sv$event_status%in%c(0,1)))
km<-fhs_km(sv,'sex1');stopifnot(inherits(km,'survfit'))
cl<-fhs_cluster(x,c('age1','sysbp1','bmi1'),c('K-means'),3)
stopifnot(nrow(cl$table)==1)
cat('PASS: core data, cleaning, splits, GLM, survival and K-means smoke checks.\n')

# Validation permutation importance for the supervised GLM.
imp <- fhs_importance(z)
stopifnot(nrow(imp)>0, all(c('feature','importance') %in% names(imp)))
# Plotly bars should be drawable for finite importance values.
stopifnot(inherits(fhs_importance_plot(imp,'Supervised model importance'),'plotly'))
# Survival comparison and its permutation importance (Cox PH, fast smoke test).
svfit <- fhs_surv_models(x,'anychd',c('age1','sex1','sysbp1'),c('Cox PH'),.7,.15)
stopifnot(nrow(svfit$table)==1)
si <- fhs_survival_importance(svfit,c('age1','sex1','sysbp1'))
stopifnot(nrow(si)==3)
cox_effects <- fhs_coefficient_intervals(svfit$models[['Cox PH']],'hazard')
stopifnot(nrow(cox_effects)>0)
cat('PASS: supervised and Cox survival model importance smoke checks.\n')
